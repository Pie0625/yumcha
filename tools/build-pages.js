// Makes one page per cafe, so each cafe has its own address like /kopi-kawan/.
//
// Run it from the project folder after you add, rename or remove a cafe in data/cafes.js:
//     node tools/build-pages.js
//
// For every cafe it creates <cafe-id>/index.html from tools/cafe-template.html,
// and it deletes folders for cafes that no longer exist.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const marker = '<!-- Generated by tools/build-pages.js. Edit tools/cafe-template.html, then run the script again. -->';

// Folder names that are already used by the site, so a cafe can't take them.
const reserved = ['home', 'community', 'supabase', 'css', 'js', 'data', 'images', 'icons', 'tools', 'node_modules'];

// data/cafes.js is a browser file, so run it in a sandbox that has a fake `window`.
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'data', 'cafes.js'), 'utf8'), sandbox);
const cafes = sandbox.window.YUMCHA_CAFES;
if (!Array.isArray(cafes) || cafes.length === 0) {
  console.error('No cafes found in data/cafes.js');
  process.exit(1);
}

const template = fs.readFileSync(path.join(__dirname, 'cafe-template.html'), 'utf8');
const escapeAttr = (t) => String(t).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const seen = new Set();
for (const cafe of cafes) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(cafe.id)) {
    console.error('Cafe id "' + cafe.id + '" must use lowercase letters, numbers and dashes only (like kopi-kawan).');
    process.exit(1);
  }
  if (reserved.includes(cafe.id) || seen.has(cafe.id)) {
    console.error('Cafe id "' + cafe.id + '" is reserved or used twice. Pick a different id.');
    process.exit(1);
  }
  seen.add(cafe.id);
}

// Remove pages of cafes that were deleted. Only folders we generated are touched.
for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
  if (!entry.isDirectory() || seen.has(entry.name)) continue;
  const page = path.join(root, entry.name, 'index.html');
  if (fs.existsSync(page) && fs.readFileSync(page, 'utf8').includes(marker)) {
    fs.rmSync(path.join(root, entry.name), { recursive: true });
    console.log('removed ' + entry.name + '/');
  }
}

for (const cafe of cafes) {
  const description = cafe.name + ' in ' + cafe.area + '. RM' + cafe.priceFrom + ' to RM' + cafe.priceTo +
    ' per person, rated ' + cafe.rating.toFixed(1) + '. ' + cafe.blurb;
  const html = template
    .replace(/{{id}}/g, cafe.id)
    .replace(/{{name}}/g, escapeAttr(cafe.name))
    .replace(/{{description}}/g, escapeAttr(description))
    .replace('<!doctype html>', '<!doctype html>\n' + marker);
  fs.mkdirSync(path.join(root, cafe.id), { recursive: true });
  fs.writeFileSync(path.join(root, cafe.id, 'index.html'), html);
}
console.log('Built ' + cafes.length + ' cafe pages.');
